CREATE OR REPLACE TABLE customers (
  customer_id BIGINT, full_name STRING, province STRING, birth_date DATE,
  registered_at TIMESTAMP, email STRING, segment STRING, updated_at TIMESTAMP
) USING DELTA;

CREATE OR REPLACE TABLE plans (
  plan_id INT, plan_name STRING, monthly_fee DECIMAL(12,2),
  data_quota_gb DECIMAL(10,2), plan_type STRING
) USING DELTA;

CREATE OR REPLACE TABLE subscriptions (
  subscription_id BIGINT, customer_id BIGINT, plan_id INT,
  started_at TIMESTAMP, ended_at TIMESTAMP, status STRING, updated_at TIMESTAMP
) USING DELTA;

CREATE OR REPLACE TABLE billing_transactions (
  transaction_id BIGINT, customer_id BIGINT, transaction_ts TIMESTAMP,
  amount DECIMAL(14,2), transaction_type STRING, payment_method STRING,
  status STRING, updated_at TIMESTAMP
) USING DELTA;

CREATE OR REPLACE TABLE cell_towers (
  tower_id INT, tower_name STRING, province STRING,
  technology STRING, commissioned_at DATE
) USING DELTA;

-- event_id deliberately NOT unique: the lab needs duplicate/versioned events.
CREATE OR REPLACE TABLE network_events (
  ingest_row_id BIGINT, event_id STRING, tower_id INT, customer_id BIGINT,
  event_type STRING, event_ts TIMESTAMP, ingested_at TIMESTAMP,
  signal_dbm DECIMAL(8,2), duration_seconds INT, payload_version INT
) USING DELTA;

CREATE OR REPLACE TABLE customer_status_history (
  status_history_id BIGINT, customer_id BIGINT, status STRING,
  effective_from TIMESTAMP, recorded_at TIMESTAMP, source_system STRING
) USING DELTA;

